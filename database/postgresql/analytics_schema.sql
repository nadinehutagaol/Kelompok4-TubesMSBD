-- Separate analytics database: trrrible_analytics
CREATE TABLE IF NOT EXISTS designer_metrics (
    designer_id BIGINT PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    total_karya BIGINT NOT NULL DEFAULT 0,
    total_likes BIGINT NOT NULL DEFAULT 0,
    refreshed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS daily_metrics (
    metric_date DATE PRIMARY KEY,
    total_shots BIGINT NOT NULL DEFAULT 0,
    total_likes BIGINT NOT NULL DEFAULT 0,
    total_comments BIGINT NOT NULL DEFAULT 0,
    active_users BIGINT NOT NULL DEFAULT 0,
    refreshed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS analytics_refresh_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refreshed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    designer_rows BIGINT NOT NULL DEFAULT 0,
    daily_rows BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'success'
);
CREATE INDEX IF NOT EXISTS designer_metrics_likes_idx ON designer_metrics (total_likes DESC);
CREATE INDEX IF NOT EXISTS daily_metrics_date_idx ON daily_metrics (metric_date DESC);
CREATE OR REPLACE VIEW view_analytics_overview AS
SELECT COALESCE(SUM(total_shots), 0) AS total_shots,
       COALESCE(SUM(total_likes), 0) AS total_likes,
       COALESCE(SUM(total_comments), 0) AS total_comments,
       COALESCE(MAX(active_users), 0) AS peak_active_users
FROM daily_metrics;
