-- Advanced database components for the Trrrible project.
-- Run on the primary database AFTER importing the original MySQL data.

CREATE TABLE IF NOT EXISTS activity_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_type VARCHAR(40) NOT NULL,
    actor_user_id BIGINT NULL,
    target_shot_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS activity_audits_created_at_idx ON activity_audits (created_at);
CREATE INDEX IF NOT EXISTS activity_audits_activity_type_idx ON activity_audits (activity_type);

-- Trigger function: records new likes/comments without changing the existing workflow.
CREATE OR REPLACE FUNCTION fn_audit_social_activity()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO activity_audits (activity_type, actor_user_id, target_shot_id)
    VALUES (TG_TABLE_NAME, NEW.user_id, NEW.shot_id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_like_insert ON likes;
CREATE TRIGGER trg_audit_like_insert
AFTER INSERT ON likes
FOR EACH ROW EXECUTE FUNCTION fn_audit_social_activity();

DROP TRIGGER IF EXISTS trg_audit_comment_insert ON comments;
CREATE TRIGGER trg_audit_comment_insert
AFTER INSERT ON comments
FOR EACH ROW EXECUTE FUNCTION fn_audit_social_activity();

-- Stored function: returns total likes + comments for a shot.
CREATE OR REPLACE FUNCTION fn_shot_engagement(p_shot_id BIGINT)
RETURNS BIGINT AS $$
DECLARE result BIGINT;
BEGIN
    SELECT
        (SELECT COUNT(*) FROM likes WHERE shot_id = p_shot_id) +
        (SELECT COUNT(*) FROM comments WHERE shot_id = p_shot_id)
    INTO result;
    RETURN COALESCE(result, 0);
END;
$$ LANGUAGE plpgsql STABLE;

-- Stored procedure: explicitly clean expired database sessions (30 days).
-- It is intentionally not scheduled automatically; administrators may call it when needed.
CREATE OR REPLACE PROCEDURE sp_cleanup_expired_sessions()
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM sessions
    WHERE last_activity < EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - INTERVAL '30 days'))::BIGINT;
END;
$$;

-- Aggregated view used for content engagement inspection.
CREATE OR REPLACE VIEW view_content_engagement AS
SELECT s.id AS shot_id, s.title, s.user_id,
       COUNT(DISTINCT l.user_id) AS total_likes,
       COUNT(DISTINCT c.id) AS total_comments
FROM shots s
LEFT JOIN likes l ON l.shot_id = s.id
LEFT JOIN comments c ON c.shot_id = s.id
GROUP BY s.id, s.title, s.user_id;
